import 'server-only'
import Anthropic from '@anthropic-ai/sdk'

// Trang /phuc-dung: AI xem khung hình từng đoạn 8 giây và viết bộ nhận dạng + kịch bản từng cảnh.
// Giống lib/troLyCV.ts: có GEMINI_API_KEY → dùng Gemini (miễn phí), không có → dùng Claude.
const MODEL_CLAUDE = 'claude-opus-5-5'
const MODEL_GEMINI = (process.env.GEMINI_MODELS ?? 'gemini-flash-latest,gemini-2.5-flash,gemini-flash-lite-latest')
  .split(',')
  .map((m) => m.trim())
  .filter(Boolean)

export type AnhDoan = { ten: string; doan: number; giay: number; jpg: string }

const SYSTEM = `You help a Vietnamese video maker rebuild a video with Google Veo 3, one 8-second shot at a time.
You receive frames from the original video. Each frame is labelled like "doan_003_giua" (segment 3, middle frame) with its time.
Segments are 8 seconds long; for each segment you get its first (dau), middle (giua) and last (cuoi) frame.

Write a JSON object with exactly this shape:
{
  "nhan_dang": {
    "phong_cach": "one English sentence: overall visual style, lens look, colour grading, lighting, aspect ratio",
    "am_thanh": "one English sentence: sound design for every shot (ambient sounds; say if there is no music)",
    "nhan_vat": [ { "ma": "A", "ten": "short Vietnamese label", "mo_ta": "English description", "anh_mau": "doan_XXX_yyy" } ],
    "boi_canh": [ { "ma": "B1", "ten": "...", "mo_ta": "...", "anh_mau": "doan_XXX_yyy" } ],
    "do_vat":   [ { "ma": "X1", "ten": "...", "mo_ta": "...", "anh_mau": "doan_XXX_yyy" } ]
  },
  "canh": [
    { "ten": "short Vietnamese title", "doan_goc": [3], "boi_canh": "B1", "nhan_vat": ["A"], "do_vat": ["X1"],
      "khung_dau": "English: exactly what the FIRST frame (doan_XXX_dau) shows",
      "khung_cuoi": "English: exactly what the LAST frame (doan_XXX_cuoi) shows",
      "hanh_dong": "English: the motion that turns the first frame into the last frame",
      "may_quay": "English: shot size, angle and camera movement", "noi_tiep": true, "co_cat_canh": false,
      "trang_thai": { "character": "...", "scene": "...", "props": "...", "action": "...", "camera": "...", "lighting": "..." } }
  ]
}

This is a RECONSTRUCTION LOCK. Rules:
- CHARACTER LOCK (nhan_vat[].mo_ta): the description is pasted word for word into EVERY shot prompt, so make it complete
  and fixed. Cover, in this order: approximate age, gender, skin tone, face shape and distinctive facial features (beard,
  eyebrows, scars, glasses…), hair style and colour, build and body proportions, every clothing item with its colour and
  material, footwear, accessories (hat, gloves, watch, bag…), any special identifying marks.
- SCENE LOCK (boi_canh[].mo_ta): location type, architecture or terrain, spatial layout (what is left / right / behind),
  where the camera usually stands relative to the scene, ground / walls / floor / doors / windows, fixed furniture and
  objects with their positions, environment colours, light source and direction, time of day, weather. Fixed objects
  keep their position, shape and look in every shot unless the action in the video changes them.
- PROP LOCK (do_vat[].mo_ta): type, size, shape, colours, materials and distinctive parts of every prop or vehicle that is
  handled or matters to the action. Do not invent props that are not visible.
- "phong_cach": visual style, lens look, colour grading, contrast, aspect ratio. "am_thanh": the ambient sound bed.
- ACTION LOCK per scene: "khung_dau" = start position, pose and gaze direction; "hanh_dong" = body movement in time
  order: what hands / feet do, how props are handled, direction and speed of movement; "khung_cuoi" = the final state.
- CONTINUITY STATE per scene ("trang_thai"): the state at the END of this segment (its last frame), short English
  phrases, used as the starting basis of the next shot: character (pose, position, gaze, what is held, visible dirt or
  changes), scene (what changed in the place), props (where each prop is and in what state), action (what was just
  finished / is about to continue), camera (shot size, angle, height, distance), lighting (light and time of day).
- Never redesign a character, never change face, hair, clothing or build, never change the setting, time of day,
  light or visual style, never add or remove props, unless the original frames really show such a change.
- If something cannot be seen clearly, write [UNCERTAIN] for that detail instead of inventing it.
- Describe people only by appearance and clothing. Never name or identify real people, never ask to copy a real face.
- Never mention brand names, logos, licence plates or written text; describe products by shape and colour instead.
- One entry in "canh" per segment you were given, in time order. "doan_goc" is that segment number.
- Each shot is generated by Veo from that segment's first frame (dau) as start image and last frame (cuoi) as end image,
  so the text must agree with BOTH images:
  * "khung_dau": look ONLY at the image labelled doan_XXX_dau and describe what is visible in it: framing (close-up /
    wide…), camera angle, who/what is where in the frame (left/centre/right, foreground/background), each person's pose,
    hands, what they hold, facing direction, and the light.
  * "khung_cuoi": look ONLY at the image labelled doan_XXX_cuoi and describe it the same way. Describe what that image
    really shows, NOT what you expect after the action. If the camera cut to a different angle or place inside the
    segment, say so: the last frame may look very different from the first.
  * "hanh_dong": the movement in between, in order (use the giua frame to know the middle), ending exactly in the
    khung_cuoi state. If there is a cut inside the segment, describe it as "then the shot cuts to …".
- "co_cat_canh": true when the first and last frames come from different camera shots (a cut inside the segment:
  different framing, angle or place), false when it is one continuous shot.
- Write each scene from its own frames only; never copy the description of a neighbouring segment.
- "noi_tiep": true when the shot directly continues the previous one (same moment), false after a cut to a new moment/place.
- "anh_mau": the label of the frame that shows that character / place / object most clearly, or "" if none.
- Reuse the same codes across shots; only create a new character/place/object when it really is different.
- Output only the JSON object, no markdown.`

// Nhãn đặt ngay trước mỗi ảnh để AI không lẫn ảnh đầu / cuối giữa các đoạn
const LOAI: Record<string, string> = { dau: 'FIRST frame', giua: 'MIDDLE frame', cuoi: 'LAST frame' }
const nhan = (a: AnhDoan) => `${a.ten} = ${LOAI[a.ten.split('_')[2]] ?? 'frame'} of segment ${a.doan} (t=${a.giay.toFixed(1)}s):`

function noiDungChu(anh: AnhDoan[], ghiChu: string, ndCu: string) {
  return (
    `Frames: ${anh.map((a) => `${a.ten} (${a.giay.toFixed(1)}s)`).join(', ')}.` +
    (ndCu
      ? '\n\nThis is a CONTINUATION: earlier shots of the same video were already generated with this nhan_dang:\n' +
        ndCu +
        '\nCopy it UNCHANGED into your output nhan_dang (same codes, same wording, same anh_mau, same phong_cach and am_thanh). ' +
        'Reuse its codes whenever the same character, place or object appears. Add a new entry (with a new code) only for ' +
        'something that is not in it. Write "canh" only for the segments in these frames.'
      : '') +
    (ghiChu ? `\nNote from the video maker (Vietnamese): ${ghiChu}` : '')
  )
}

// ndCu: bộ nhận dạng (JSON) của các cảnh đã làm khi "làm tiếp" đợt sau, để AI giữ nguyên
export async function vietKichBan(anh: AnhDoan[], ghiChu: string, ndCu = ''): Promise<unknown> {
  const chu = noiDungChu(anh, ghiChu, ndCu)
  const text = process.env.GEMINI_API_KEY ? await hoiGemini(anh, chu) : await hoiClaude(anh, chu)
  if (!text) return null
  const json = text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1)
  try {
    return JSON.parse(json)
  } catch {
    return null
  }
}

async function hoiGemini(anh: AnhDoan[], chu: string): Promise<string | null> {
  const parts = anh.flatMap((a) => [{ text: nhan(a) }, { inline_data: { mime_type: 'image/jpeg', data: a.jpg } }])
  for (const model of MODEL_GEMINI) {
    const res = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'x-goog-api-key': process.env.GEMINI_API_KEY! },
      body: JSON.stringify({
        systemInstruction: { parts: [{ text: SYSTEM }] },
        contents: [{ role: 'user', parts: [...parts, { text: chu }] }],
        generationConfig: { responseMimeType: 'application/json' },
      }),
      signal: AbortSignal.timeout(120_000),
    }).catch(() => null)
    if (!res) continue
    const data = (await res.json().catch(() => ({}))) as {
      candidates?: { content?: { parts?: { text?: string }[] } }[]
    }
    const text = (data.candidates?.[0]?.content?.parts ?? []).map((p) => p.text ?? '').join('').trim()
    if (res.ok && text) return text
    // Quá tải / hết lượt → thử model kế tiếp
  }
  return null
}

let client: Anthropic | null = null

async function hoiClaude(anh: AnhDoan[], chu: string): Promise<string | null> {
  client ??= new Anthropic()
  const res = await client.messages.create({
    model: MODEL_CLAUDE,
    max_tokens: 16000,
    system: SYSTEM,
    messages: [
      {
        role: 'user',
        content: [
          ...anh.flatMap((a) => [
            { type: 'text' as const, text: nhan(a) },
            { type: 'image' as const, source: { type: 'base64' as const, media_type: 'image/jpeg' as const, data: a.jpg } },
          ]),
          { type: 'text' as const, text: chu },
        ],
      },
    ],
  })
  if (res.stop_reason === 'refusal') return null
  return res.content.map((b) => (b.type === 'text' ? b.text : '')).join('').trim() || null
}
